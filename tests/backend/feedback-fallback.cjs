const assert = require("node:assert/strict");
const { pathToFileURL } = require("node:url");
const root = require("node:path").resolve(__dirname, "../..") + "/";
require("node:module").registerHooks({ resolve(s, c, next) {
  if (s === "server-only") return { url: "data:text/javascript,export%20%7B%7D", shortCircuit: true };
  if (s.startsWith("@/")) return { url: pathToFileURL(root + s.slice(2) + ".ts").href, shortCircuit: true };
  if (s.startsWith("./") && c.parentURL?.startsWith(pathToFileURL(root + "lib/").href) && !s.endsWith(".ts")) return { url: new URL(s + ".ts", c.parentURL).href, shortCircuit: true };
  if (s === "next/server") return { url: pathToFileURL(root + "node_modules/next/server.js").href, shortCircuit: true };
  return next(s, c);
}});
(async () => {
  delete process.env.PRISMTRACE_API_KEY;
  delete process.env.THESIS_RANKER_URL;
  const feedback = require(root + "app/api/feedback/route.ts");
  const signals = require(root + "app/api/signals/route.ts");
  const seed = require(root + "lib/seededAktaData.json").data;
  const before = JSON.stringify(seed);
  const post = (body) => feedback.POST(new Request("http://local/api/feedback", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) }));
  let calls = [];
  global.fetch = async (url, options) => {
    calls.push({ url: String(url), body: options.body && JSON.parse(options.body) });
    if (String(url).endsWith("/action")) return Response.json({ n_actions: 1, remaining: 49, readback_pending: false });
    return Response.json({ fitted: true, n_actions: 2, ranked: [{ id: seed[1].id, score: 0.9, reasons: ["sector"] }] });
  };
  let response = await post({ id: seed[0].id, action: "save" });
  let body = await response.json();
  assert.equal(response.status, 200); assert.equal(body.meta.backend, "python");
  assert.equal(calls[0].url, "http://localhost:8000/action");
  assert.deepEqual(calls[0].body, { uuid: seed[0].id, action: "save" });
  response = await signals.GET(new Request("http://local/api/signals")); body = await response.json();
  assert.equal(body.data.length, 50); assert.equal(body.data[0].id, seed[1].id); assert.equal(body.meta.ranking.source, "model");
  global.fetch = async () => { throw Error("ECONNREFUSED"); };
  response = await post({ uuid: seed[1].id, action: "intro" }); body = await response.json();
  assert.equal(response.status, 200); assert.equal(body.meta.backend, "typescript");
  response = await signals.GET(new Request("http://local/api/signals")); body = await response.json();
  assert.equal(body.data.length, 50); assert.equal(body.meta.ranking.backend, "typescript");
  assert(body.data.every(p => p.learnedMatch.probability === null));
  assert.notEqual(body.data[0].id, seed[0].id);
  assert.equal((await post({ id: seed[1].id, action: "intro" })).status, 200);
  assert.equal((await post({ id: seed[1].id, action: "pass" })).status, 409);
  assert.equal((await post({ id: "missing", action: "pass" })).status, 404);
  assert.equal((await post({ id: seed[2].id, action: "wrong" })).status, 400);
  response = await feedback.POST(new Request("http://local/api/feedback", { method: "POST", headers: { "Content-Type": "application/json" }, body: "{" }));
  assert.equal(response.status, 400);
  global.fetch = () => new Promise(() => {});
  const start = performance.now();
  response = await post({ id: seed[2].id, action: "track" });
  assert.equal(response.status, 200); assert(performance.now() - start < 1500);
  response = await signals.GET(new Request("http://local/api/signals?thesis=AI%20Agents")); body = await response.json();
  assert(body.data.length > 0 && body.data.length < 50); assert(body.data.every(p => p.thesisMatch.matched));
  assert.equal(JSON.stringify(seed), before);
  console.log("PASS: default localhost proxy, offline feedback/ranking, validation, duplicate handling, hanging service deadline, thesis isolation, unchanged seed");
})().catch(error => { console.error(error); process.exitCode = 1; });
